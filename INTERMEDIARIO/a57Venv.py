# Ambientes virtuais em Python (venv)
# Um ambiente virtual carrega toda a sua instalação
# do Python para uma pasta no caminho escolhido.
# Ao ativar um ambiente virtual, a instalação do
# ambiente virtual será usada.
# venv é o módulo que vamos usar para
# criar ambientes virtuais.
# Você pode dar o nome que preferir para um
# ambiente virtual, mas os mais comuns são:
# venv env .venv .env

# ambientevenv\Scripts\Activate # Ativa ambiente virtual

# deactivate # Desativa ambiente virtual

# .\ambientevenv\Scripts\activate # Ativa ambiente virtual

# gcm python.exe -Syntax # Ve o caminho do ambiente virtual

# pip --version # Onde o que for baixado sera armazenado (pode ser ambiente global ou virtual)
