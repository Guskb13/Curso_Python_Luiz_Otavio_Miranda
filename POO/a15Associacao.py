# Relações entre classes: associação, agregação e composição
# Associação é um tipo de relação onde os objetos
# estão ligados dentro do sistema.
# Essa é a relação mais comum entre objetos e tem subconjuntos
# como agregação e composição (que veremos depois).
# Geralmente, temos uma associação quando um objeto tem
# um atributo que referencia outro objeto.
# A associação não especifica como um objeto controla
# o ciclo de vida de outro objeto.


# ASSOCIAÇÃO: UM OBJETO COMUNICA COM OUTRO OBJETO
# Um objeto usa outro

""" 
Escritor usa uma FerramentaDeEscrever, mas:
A ferramenta existe independentemente do escritor
Pode ser trocada a qualquer momento
Não é criada nem destruída junto com o escritor

O Escritor apenas referencia a Ferramenta
Não é dono dela
Pode trocar, remover ou nunca ter
A Ferramenta não sabe que o Escritor existe

Uma classe conhece/usa a outra, sem relação de “dono”
"""


class Escritor:
    def __init__(self, nome):
        self.nome = nome
        self._ferramenta = None

    @property
    def ferramenta(self):
        return self._ferramenta

    @ferramenta.setter
    def ferramenta(self, ferramenta):
        self._ferramenta = ferramenta


class FerramentaDeEscrever:
    def __init__(self, nome):
        self.nome = nome

    def escrever(self):
        return f'{self.nome} está escrevendo'


escritor = Escritor('Vitor')
caneta = FerramentaDeEscrever('Caneta Bic')
maquina_de_escrever = FerramentaDeEscrever('Máquina')
escritor.ferramenta = maquina_de_escrever

print(caneta.escrever())
print(maquina_de_escrever.escrever())
print(escritor.ferramenta.escrever())